// Bundles rules/*.json into packages/core/src/rules.js so `npm install tellbuster` works with no extra files.
// Run from the repo root after changing any rules file: node scripts/sync-core-rules.js
import { readFileSync, readdirSync } from 'node:fs';
import { writeIfChanged } from './write-if-changed.js';

const root = new URL('../', import.meta.url);
const files = readdirSync(new URL('rules/', root)).filter((f) => f.endsWith('.json')).sort();
const packs = {};
for (const f of files) packs[f.replace(/\.json$/, '')] = JSON.parse(readFileSync(new URL(`rules/${f}`, root), 'utf8'));

const out = `// Generated by scripts/sync-core-rules.js from rules/*.json. Do not edit by hand.\nexport const packs = ${JSON.stringify(packs, null, 2)};\n`;
writeIfChanged(new URL('packages/core/src/rules.js', root), out);
console.log(`Bundled ${files.join(', ')} into packages/core/src/rules.js`);
